/**
 * Generates data/vehicles.ts from the six vehicle pages, and extends the route
 * map so every `toyota-camry.html` style link becomes `/fleet/toyota-camry`.
 *
 * Specs are read out of each page rather than typed by hand, so the seat and
 * luggage counts cannot drift from the original.
 */
import { readFile, writeFile } from 'node:fs/promises';

const VEHICLES = [
  'toyota-camry',
  'hyundai-sonata',
  'hyundai-staria',
  'gmc-xl-yukon',
  'hiace-grand-cabin',
  'coaster',
];

const dec = (s) =>
  String(s ?? '')
    .replace(/&amp;amp;/g, '&').replace(/&amp;/g, '&').replace(/&nbsp;/g, ' ')
    .replace(/&quot;/g, '"').replace(/&#0?39;/g, "'");
const clean = (s) => dec(String(s).replace(/<[^>]+>/g, ' ')).replace(/\s+/g, ' ').trim();
const q = (v) => (v == null ? 'null' : JSON.stringify(v));

const rows = [];
for (const slug of VEHICLES) {
  const file = `${slug}.html`;
  const h = await readFile(`_reference/${file}`, 'utf8');

  const title = clean((h.match(/<title[^>]*>([\s\S]*?)<\/title>/i) || [, ''])[1]);

  // The page body: <h1> name, a tagline, "Vehicle Overview", two spec lines,
  // a description paragraph, then the booking button.
  const body = h.slice(h.indexOf('page-body'));
  const text = clean(body.replace(/<script[\s\S]*?<\/script>/gi, ''));

  const pax = (text.match(/Up to (\d+) Passengers?/i) || [, null])[1];
  const bags = (text.match(/Up to (\d+) Large Bags?/i) || [, null])[1];

  // Tagline is the line between the h1 and "Vehicle Overview".
  const h1 = clean((body.match(/<h1[^>]*>([\s\S]*?)<\/h1>/i) || [, ''])[1]);
  const between = text.slice(text.indexOf(h1) + h1.length, text.indexOf('Vehicle Overview')).trim();

  // Description is the paragraph after the two spec lines.
  const afterBags = text.slice(text.indexOf('Large Bags') + 'Large Bags'.length);
  const desc = afterBags.slice(0, afterBags.indexOf('Book This Vehicle')).trim();

  const mainImg = (body.match(/<img\b[^>]*src=["']((?!.*LOGO)[^"']+)["']/i) || [, null])[1];

  rows.push({
    slug,
    source: file,
    title,
    name: h1,
    tagline: between,
    passengers: pax ? Number(pax) : null,
    largeBags: bags ? Number(bags) : null,
    description: desc,
    image: mainImg ? '/' + mainImg.replace(/^\//, '') : null,
  });
}

await writeFile(
  'data/vehicles.ts',
  `// AUTO-GENERATED by _gen-vehicles.mjs — do not edit by hand.
//
// The six vehicles that have their own page on the original. Specs are read out
// of each page rather than retyped, so seat and luggage counts cannot drift.
//
// Note: the original's booking engine carries ten vehicles with different
// capacities (e.g. it quotes the Hiace at 10 passengers where this page says 11).
// These are the marketing pages' numbers, reproduced as published.

export type Vehicle = {
  /** Route segment: /fleet/<slug>. */
  slug: string;
  /** Reference file this page is replicated from. */
  source: string;
  /** The original page's <title>, carried over unchanged. */
  title: string;
  /** <h1> on the vehicle page. */
  name: string;
  tagline: string;
  passengers: number | null;
  largeBags: number | null;
  description: string;
  image: string | null;
};

export const vehicles: Vehicle[] = [
${rows
  .map(
    (v) =>
      `  {\n    slug: ${q(v.slug)},\n    source: ${q(v.source)},\n    title: ${q(v.title)},\n    name: ${q(v.name)},\n    tagline: ${q(v.tagline)},\n    passengers: ${v.passengers},\n    largeBags: ${v.largeBags},\n    description: ${q(v.description)},\n    image: ${q(v.image)},\n  },`,
  )
  .join('\n')}
];

export const vehicleBySlug = (slug: string) => vehicles.find((v) => v.slug === slug);
`,
);

// extend the route map
const map = JSON.parse(await readFile('_route-map.json', 'utf8'));
map['all-fleet.html'] = '/fleet';
for (const v of rows) map[v.source] = `/fleet/${v.slug}`;
await writeFile('_route-map.json', JSON.stringify(map, null, 2));

console.log(`vehicles: ${rows.length}`);
for (const v of rows) {
  console.log(
    `  ${v.slug.padEnd(19)} ${String(v.passengers ?? '?').padStart(2)} pax / ${String(v.largeBags ?? '?').padStart(2)} bags   ${v.name}`,
  );
  console.log(`      tagline: ${v.tagline}`);
}
console.log(`\nroute map now ${Object.keys(map).length} entries (+ /fleet and 6 vehicles)`);
